import assert from 'node:assert/strict'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { mkdir } from 'node:fs/promises'
import { chromium } from '@playwright/test'
import { createServer } from 'vite'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const evidence = path.join(root, 'docs/migration/phase-15/evidence/restoration-e')
const server = await createServer({ configFile: path.join(root, 'vite.config.js'), envFile: false, server: { host: '127.0.0.1', port: 5187, strictPort: true } })
await server.listen()
const browser = await chromium.launch({ headless: true })
await mkdir(evidence, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
page.setDefaultTimeout(12000)
page.setDefaultNavigationTimeout(30000)
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
const mount = async (module, role = 'employee', extra = '') => {
  await page.goto(`http://127.0.0.1:5187/tests/portal-restoration-e.html?module=${module}&role=${role}${extra}`)
  await page.locator('.portal.app-layout').waitFor()
  if (module === 'training') {
    await page.getByRole('heading', { name: /Training & Certifications/ }).waitFor()
    if (!extra.includes('unavailable=true')) await page.locator('.staff-record').first().waitFor()
  }
}
const failNext = () => page.evaluate(() => { window.__restorationFailNext = true })
const screenshot = (name) => page.screenshot({ path: path.join(evidence, `${name}.png`), fullPage: true })
const calls = () => page.evaluate(() => window.__restorationRequests)
try {
  for (const role of ['employee', 'manager']) {
    await mount('home', role)
    await page.getByRole('heading', { name: role === 'manager' ? 'Sam Taylor' : 'Alex Morgan', exact: true }).waitFor()
    await page.getByRole('heading', { name: "Today's status" }).waitFor()
    assert.equal(await page.getByRole('button', { name: /Clock in|Clock out/i }).count(), 0)
    assert.match(await page.locator('.sidebar-logo').innerText(), /Synthetic Clinic/)
    await screenshot(`${role}-home-desktop`)
    await mount('profile', role)
    await page.getByRole('button', { name: 'Edit contact details' }).click()
    await page.getByLabel('Personal email', { exact: true }).fill('changed@example.test')
    await failNext()
    await page.getByRole('button', { name: 'Save contact details' }).click()
    await page.getByRole('alert').filter({ hasText: 'could not be saved' }).waitFor()
    assert.equal(await page.getByLabel('Personal email', { exact: true }).inputValue(), 'changed@example.test')
    await page.getByRole('button', { name: 'Save contact details' }).click()
    await page.getByText('Contact details saved.', { exact: true }).waitFor()
    const contact = (await calls()).filter((item) => item.path.endsWith('/contact')).at(-1)
    assert.deepEqual(Object.keys(contact.options.json).sort(), ['emergencyContactName', 'emergencyContactPhone', 'expectedUpdatedAt', 'personalEmail', 'phone'])
    await screenshot(`${role}-profile-desktop`)

    await mount('training', role)
    if (role === 'manager') await page.getByRole('tab', { name: 'My Training', exact: true }).click()
    await page.getByRole('button', { name: 'Record my result' }).waitFor()
    await page.getByRole('button', { name: 'Record my result' }).click()
    let dialog = page.getByRole('dialog')
    assert.equal(await dialog.getByLabel('Counts toward CME').count(), 0)
    await dialog.getByLabel('Score', { exact: true }).fill('92%')
    await failNext()
    await dialog.getByRole('button', { name: 'Save my result' }).click()
    await dialog.getByRole('alert').waitFor()
    assert.equal(await dialog.getByLabel('Score', { exact: true }).inputValue(), '92%')
    await dialog.getByRole('button', { name: 'Save my result' }).click()
    await dialog.waitFor({ state: 'detached' })
    await page.getByText('Self-reported result. No verified CME credit.', { exact: true }).waitFor()
    const results = (await calls()).filter((item) => item.path.endsWith('/self-complete'))
    assert.equal(results.length, 2)
    assert.deepEqual(results[0].options, results[1].options)
    assert.deepEqual(Object.keys(results[1].options.json).sort(), ['durationHours', 'endDate', 'expectedUpdatedAt', 'passed', 'score'])
    assert.equal(results[1].options.headers['X-Workloop-Branch-ID'], undefined)
    await screenshot(`${role}-training-result-desktop`)
    await page.getByRole('heading', { name: 'Basic life support' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Verify', exact: true }).count(), 0)

    await mount('appraisals', role)
    if (role === 'manager') await page.getByRole('tab', { name: 'My Appraisal', exact: true }).click()
    const appraisal = page.getByRole('button', { name: /H2 2026/ }).first()
    await appraisal.focus(); await page.keyboard.press('Enter')
    await page.getByText('Your appraisal is read-only.', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Rate section', exact: true }).count(), 0)
    await screenshot(`${role}-appraisal-desktop`)
    await mount('payslips', role)
    await page.getByRole('button', { name: /2026-09/ }).click()
    await page.getByRole('heading', { name: 'Earnings', exact: true }).waitFor()
    await failNext(); await page.getByRole('button', { name: 'Open printable PDF' }).click()
    await page.getByRole('alert').filter({ hasText: 'remains open' }).waitFor()
    assert.equal(await page.getByRole('heading', { name: 'Earnings', exact: true }).count(), 1)
    await screenshot(`${role}-payslip-desktop`)

    await mount('schedule', role)
    await page.getByRole('button', { name: 'Swap', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('Colleague shift date').fill('2026-10-13')
    await dialog.locator('select').nth(1).selectOption('e5000000-0000-4000-8000-000000000006')
    await dialog.getByLabel('Reason').fill('Family appointment')
    await failNext(); await dialog.getByRole('button', { name: 'Request swap' }).click()
    await dialog.getByRole('alert').waitFor()
    assert.equal(await dialog.getByLabel('Reason').inputValue(), 'Family appointment')
    await dialog.getByRole('button', { name: 'Request swap' }).click()
    await dialog.waitFor({ state: 'detached' })
    await screenshot(`${role}-schedule-desktop`)
    await mount('attendance', role)
    await page.getByRole('button', { name: 'Request Attendance Correction' }).click()
    await page.getByLabel('Reason').fill('Missing clock-out')
    await failNext(); await page.getByRole('button', { name: 'Submit correction' }).click()
    await page.getByRole('alert').waitFor()
    assert.equal(await page.getByLabel('Reason').inputValue(), 'Missing clock-out')
    await page.getByRole('button', { name: 'Submit correction' }).click()
    await page.getByText('Attendance correction submitted for review.', { exact: true }).waitFor()
    const corrections = (await calls()).filter((item) => item.path === '/api/v1/attendance/regularisations' && item.options.method === 'POST')
    assert.deepEqual(corrections[0].options, corrections[1].options)
    assert.match(corrections[1].options.json.correctClockIn, /T04:00:00.000Z$/)
    await screenshot(`${role}-attendance-desktop`)
    await mount('leave', role)
    await page.locator('.personal-leave-card summary').first().focus()
    await page.keyboard.press('Enter')
    await page.getByText('Reason: Family commitment', { exact: true }).waitFor()
    await page.getByRole('tab', { name: 'Balances', exact: true }).click()
    await page.locator('.leave-balance-card').waitFor()
    await page.getByRole('tab', { name: 'Calendar', exact: true }).click()
    assert.equal(await page.getByRole('columnheader').first().textContent(), 'Mon')

    await mount('requests', role)
    const custom = page.getByRole('row').filter({ hasText: 'Shift change request' }).first()
    assert.equal(await custom.getByRole('button', { name: /PDF|source/ }).count(), 0)
    await page.getByRole('tab', { name: 'Custom requests' }).click()
    await page.getByLabel('Subject', { exact: true }).fill('Shift coverage request')
    await page.getByLabel('Details', { exact: true }).fill('Please review next month coverage.')
    await failNext(); await page.getByRole('button', { name: 'Submit request', exact: true }).click()
    await page.getByText(/Your entries have been kept/).waitFor()
    assert.equal(await page.getByLabel('Details').inputValue(), 'Please review next month coverage.')
    await page.getByRole('button', { name: 'Submit request', exact: true }).click()
    await page.getByText('Request submitted.', { exact: true }).waitFor()
    assert.equal((await calls()).filter((item) => item.options.method === 'POST').at(-1).options.headers['X-Workloop-Branch-ID'], undefined)
    await screenshot(`${role}-custom-request-desktop`)
    await mount('expenses', role)
    await page.getByRole('button', { name: 'View receipt', exact: true }).waitFor()
    await failNext(); await page.getByRole('button', { name: 'View receipt', exact: true }).click()
    await page.getByText('Synthetic rejected write', { exact: true }).waitFor()
    assert.equal(await page.getByText('Clinical supplies transport', { exact: true }).count(), 1)
    await page.getByRole('button', { name: 'View receipt', exact: true }).click()
    assert.equal((await calls()).filter((item) => item.path.endsWith('/receipt-download')).at(-1).options.headers?.['X-Workloop-Branch-ID'], undefined)
  }

  await mount('training', 'manager')
  await page.getByLabel('Team member').selectOption('e5000000-0000-4000-8000-000000000006')
  await page.getByRole('button', { name: 'Complete training' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Counts toward CME').check()
  await dialog.getByRole('button', { name: 'Save record' }).click()
  await dialog.waitFor({ state: 'detached' })
  const completion = (await calls()).find((item) => item.path.endsWith('/complete'))
  assert.equal(completion.options.json.isCme, true)
  await screenshot('manager-team-training-desktop')
  await page.getByRole('tab', { name: 'My Training', exact: true }).click()
  assert.equal(await page.getByLabel('Team member').count(), 0)
  await screenshot('manager-own-training-desktop')
  await mount('training', 'manager')
  assert.equal(await page.getByLabel('Team member').inputValue(), '')
  assert.ok((await calls()).some((item) => item.path.includes('/training-records/direct-reports?employeeId=')))
  assert.equal((await calls()).filter((item) => /\/(training-records|certifications)\/self/.test(item.path)).length, 0)
  await page.getByRole('tab', { name: 'Certifications', exact: true }).click()
  await page.getByRole('button', { name: 'Add Certification', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Team member for new record').selectOption('e5000000-0000-4000-8000-000000000006')
  await dialog.getByLabel('Name', { exact: true }).fill('Clinical safety')
  await dialog.getByLabel('Issuing body', { exact: true }).fill('Synthetic centre')
  await dialog.getByRole('button', { name: 'Save record' }).click()
  await dialog.waitFor({ state: 'detached' })
  assert.equal((await calls()).find((item) => item.path.endsWith('/certifications/direct-reports') && item.options.method === 'POST').options.json.employeeId, 'e5000000-0000-4000-8000-000000000006')
  await mount('appraisals', 'manager')
  await page.getByRole('button', { name: /Jamie Lee/ }).click()
  await page.getByRole('button', { name: 'Rate section' }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Comments').fill('Current report review')
  await failNext(); await dialog.getByRole('button', { name: 'Save review' }).click()
  await dialog.getByRole('alert').waitFor()
  assert.equal(await dialog.getByLabel('Comments').inputValue(), 'Current report review')
  await dialog.getByRole('button', { name: 'Save review' }).click()
  await dialog.waitFor({ state: 'detached' })
  await screenshot('manager-team-appraisal-desktop')

  for (const role of ['employee', 'manager']) for (const module of ['leave', 'advances', 'expenses', 'documents', 'requests', 'tasks', ...(role === 'manager' ? ['leave-queue', 'expense-queue', 'team'] : [])]) {
    await mount(module, role)
    await page.waitForTimeout(180)
    assert.deepEqual(await page.evaluate(() => window.__restorationUnhandled), [], `${role}/${module}`)
    assert.equal(await page.getByText(/unavailable/i).count(), 0, `${role}/${module} populated read`)
    await screenshot(`${role}-${module}-desktop`)
  }
  await mount('leave-queue', 'manager')
  await page.getByRole('button', { name: 'Reject', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Rejection reason').fill('Coverage unavailable')
  await failNext(); await dialog.getByRole('button', { name: 'Reject request' }).click()
  await dialog.getByRole('alert').waitFor()
  await dialog.getByRole('button', { name: 'Reject request' }).click()
  await dialog.waitFor({ state: 'detached' })

  for (const role of ['employee', 'manager']) {
    await page.setViewportSize({ width: 390, height: 844 })
    for (const module of ['home', 'profile', 'leave', 'schedule', 'attendance', 'payslips', 'advances', 'expenses', 'training', 'appraisals', 'documents', 'requests', 'tasks', ...(role === 'manager' ? ['leave-queue', 'expense-queue', 'team'] : [])]) {
      await mount(module, role, '&dark=true')
      await page.waitForTimeout(140)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${role}/${module} horizontal overflow`)
      await screenshot(`${role}-${module}-mobile-dark`)
    }
    await mount('training', role, '&unavailable=true')
    if (role === 'manager') await page.getByRole('tab', { name: 'My Training', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Development records are unavailable' }).waitFor()
    assert.equal(await page.getByText('No training records on file yet.', { exact: true }).count(), 0)
    await screenshot(`${role}-training-unavailable`)
  }
  assert.deepEqual(errors, [])
  console.log('Part E populated staff portals, scoped forms, retained failures, result provenance, and mobile checks passed.')
} catch (error) { console.error(await page.locator('body').innerText()); console.error(await calls()); throw error }
finally { await browser.close(); await server.close() }
