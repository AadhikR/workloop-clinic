import assert from 'node:assert/strict'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { mkdir } from 'node:fs/promises'
import { chromium } from '@playwright/test'
import { createServer } from 'vite'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const evidence = process.env.PORTAL_RESTORATION_EVIDENCE_DIR ? path.resolve(process.env.PORTAL_RESTORATION_EVIDENCE_DIR) : path.join(root, 'docs/migration/phase-15/evidence/restoration-d')
const server = await createServer({ configFile: path.join(root, 'vite.config.js'), envFile: false, server: { host: '127.0.0.1', port: 5186, strictPort: true } })
await server.listen()
const browser = await chromium.launch({ headless: true })
await mkdir(evidence, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
const errors = []
const pdfDownloads = []
page.context().on('page', (child) => child.on('download', (download) => pdfDownloads.push(download)))
page.on('pageerror', (error) => errors.push(error.message))
const mount = async (module, extra = '') => { await page.goto(`http://127.0.0.1:5186/tests/portal-restoration-d.html?module=${module}${extra}`); await page.locator('main').waitFor() }
const screenshot = (name) => page.screenshot({ path: path.join(evidence, `${name}.png`), fullPage: true })
const failNext = () => page.evaluate(() => { window.__restorationFailNext = true })
try {
  await mount('dashboard')
  await page.getByRole('heading', { name: 'Setup checklist' }).waitFor()
  await page.getByRole('heading', { name: 'Emiratization / Nafis compliance' }).waitFor()
  const employeeReview = page.locator('.dashboard-attention a').first()
  await employeeReview.focus()
  assert.equal(await employeeReview.getAttribute('href'), '/admin/employees')
  await screenshot('dashboard-desktop')
  await mount('clinical')
  await page.locator('[data-card-code="credentialsExpiring"] button').click()
  await page.getByRole('link', { name: 'Open work area' }).waitFor()
  await screenshot('clinical-desktop')

  await mount('reports')
  await page.getByRole('cell', { name: 'Alex Morgan' }).waitFor()
  for (const [family, reports] of Object.entries({ workforce: ['headcount', 'salaryMovement', 'turnover', 'eosLiability'], payroll: ['payrollCost', 'wpsCompliance', 'emiratization'], leave: ['leaveUtilization', 'leaveBalance'], attendance: ['attendanceSummary', 'overtime', 'staffingCompliance'], documents: ['documentExpiry'] })) {
    await page.getByLabel('Report family').selectOption(family)
    for (const report of reports) {
      await page.getByLabel('Report type').selectOption(report)
      await page.locator(`[data-report-family="${report}"] tbody tr`).waitFor()
      assert.ok(await page.locator(`[data-report-family="${report}"] th`).count() > 1)
    }
  }
  await page.getByLabel('Report family').selectOption('payroll')
  await page.getByLabel('Period', { exact: true }).fill('2026-10')
  await page.getByRole('cell', { name: '10000.00' }).waitFor()
  await failNext()
  await page.getByRole('button', { name: 'Download CSV' }).click()
  await page.getByRole('alert').filter({ hasText: 'preview and filters' }).waitFor()
  assert.equal(await page.getByLabel('Period', { exact: true }).inputValue(), '2026-10')
  assert.equal(await page.getByRole('cell', { name: '10000.00' }).count(), 1)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download CSV' }).click()
  assert.equal((await download).suggestedFilename(), 'synthetic.csv')
  const outputCall = await page.evaluate(() => window.__restorationRequests.filter((item) => item.options.responseType === 'bytes').at(-1))
  assert.match(outputCall.path, /period=2026-10/)
  assert.equal(outputCall.options.headers['X-Workloop-Branch-ID'], 'd4000000-0000-4000-8000-000000000002')
  const popup = page.waitForEvent('popup')
  await page.getByRole('button', { name: 'Open PDF' }).click()
  const viewer = await popup
  await page.waitForTimeout(300)
  assert.equal(await viewer.evaluate(() => window.opener), null)
  assert.ok(viewer.url().startsWith('blob:') || pdfDownloads.some((item) => item.suggestedFilename().endsWith('.pdf')))
  const pdfCall = await page.evaluate(() => window.__restorationRequests.filter((item) => item.path.includes('.pdf')).at(-1))
  assert.match(pdfCall.path, /payrollCost.pdf\?period=2026-10/)
  assert.equal(await page.getByRole('alert').count(), 0)
  await viewer.close()
  await screenshot('reports-desktop')

  for (const role of ['admin', 'manager', 'employee']) {
    await mount('tasks', `&role=${role}`)
    const group = page.getByRole('button', { name: /Expense decisions/ })
    await group.waitFor()
    assert.equal(await page.getByRole('link', { name: /Review Alex/ }).getAttribute('href'), role === 'manager' ? '/manager/expense-queue' : `/${role}/expenses`)
    await group.focus()
    await page.keyboard.press('Enter')
    assert.equal(await group.getAttribute('aria-expanded'), 'false')
    await page.keyboard.press('Enter')
    await page.getByRole('alert').filter({ hasText: 'source is unavailable' }).waitFor()
    const call = await page.evaluate(() => window.__restorationRequests.find((item) => item.path.includes('/tasks')))
    assert.equal(Object.hasOwn(call.options.headers, 'X-Workloop-Branch-ID'), role === 'admin')
    await mount('notifications', `&role=${role}`)
    await page.getByRole('button', { name: /Notifications/ }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByText('October payslip available', { exact: true }).waitFor()
    await failNext()
    await dialog.getByRole('button', { name: 'Mark all read' }).click()
    await dialog.getByRole('alert').waitFor()
    assert.equal(await dialog.getByText('October payslip available', { exact: true }).count(), 1)
    await dialog.getByRole('button', { name: 'Mark all read' }).click()
    await dialog.getByText('0 unread', { exact: true }).waitFor()
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'detached' })
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert.match(await page.locator(':focus').getAttribute('aria-label'), /Notifications/)
  }

  await mount('payroll')
  await page.getByRole('button', { name: 'Routing settings' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Bank routing code').fill('987654321')
  await failNext()
  await dialog.getByRole('button', { name: 'Save routing code' }).click()
  await dialog.getByRole('alert').waitFor()
  assert.equal(await dialog.getByLabel('Bank routing code').inputValue(), '987654321')
  await dialog.getByRole('button', { name: 'Save routing code' }).click()
  await dialog.waitFor({ state: 'detached' })
  const attempts = await page.evaluate(() => window.__restorationRequests.filter((item) => item.path.endsWith('/payroll-routing') && item.options.method === 'POST'))
  assert.equal(attempts.length, 2)
  assert.deepEqual(attempts[0].options, attempts[1].options)
  await page.getByRole('button', { name: 'Open 2026-10' }).click()
  await page.getByRole('button', { name: 'Alex Morgan', exact: true }).click()
  await page.getByRole('heading', { name: 'WPS split' }).waitFor()
  await page.keyboard.press('Escape')
  await screenshot('payroll-desktop')

  await mount('advances')
  await page.getByRole('button', { name: /New Advance/ }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Employee *', { exact: true }).selectOption('d4000000-0000-4000-8000-000000000003')
  await dialog.getByLabel('Advance Amount (AED) *').fill('1200')
  await dialog.getByLabel('Reason *', { exact: true }).fill('Synthetic travel')
  await failNext()
  await dialog.getByRole('button', { name: 'Create Advance' }).click()
  await page.getByText('Synthetic rejected write', { exact: true }).waitFor()
  assert.equal(await dialog.getByLabel('Reason *', { exact: true }).inputValue(), 'Synthetic travel')
  await dialog.getByRole('button', { name: 'Create Advance' }).click()
  await dialog.waitFor({ state: 'detached' })
  await screenshot('advances-desktop')

  await mount('expenses')
  await failNext()
  await page.getByRole('button', { name: 'View receipt' }).click()
  await page.getByText('Synthetic rejected write', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'View receipt' }).count(), 1)
  await page.getByRole('button', { name: 'Reject', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Reason *').fill('Missing approval')
  await failNext()
  await dialog.getByRole('button', { name: 'Reject Expense Claim' }).click()
  await page.getByText('Synthetic rejected write', { exact: true }).waitFor()
  assert.equal(await dialog.getByLabel('Reason *').inputValue(), 'Missing approval')
  await dialog.getByRole('button', { name: 'Reject Expense Claim' }).click()
  await dialog.waitFor({ state: 'detached' })
  await screenshot('expenses-desktop')

  await mount('wps')
  await page.getByRole('button', { name: 'Preview SIF', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('heading', { name: /SIF preview/ }).waitFor()
  await dialog.getByRole('cell', { name: 'AE070331234567890123456' }).waitFor()
  await failNext()
  await dialog.getByRole('button', { name: 'Download SIF' }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await dialog.count(), 1)
  const sifDownload = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Download SIF' }).click()
  assert.equal((await sifDownload).suggestedFilename(), 'synthetic.sif')
  await screenshot('sif-desktop')
  await page.keyboard.press('Escape')
  await mount('wps', '&role=employee')
  assert.equal(await page.getByRole('button').count(), 0)
  assert.equal((await page.evaluate(() => window.__restorationRequests)).length, 0)

  await mount('settings')
  await page.getByRole('button', { name: 'Change payroll routing code' }).click()
  await page.getByRole('dialog').getByLabel('Bank routing code').fill('987654321')
  await page.getByRole('button', { name: 'Save routing code' }).click()
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  assert.equal(await page.getByLabel('Default bank routing code').inputValue(), '987654321')

  await page.setViewportSize({ width: 390, height: 844 })
  for (const module of ['dashboard', 'clinical', 'reports', 'tasks', 'payroll', 'advances', 'expenses', 'wps']) {
    await mount(module, '&dark=1')
    await page.waitForTimeout(200)
    if (module === 'wps') {
      await page.getByRole('button', { name: 'Preview SIF' }).click()
      await page.getByRole('dialog').waitFor()
      assert.equal(await page.getByRole('dialog').evaluate((node) => getComputedStyle(node).backgroundColor), 'rgb(15, 23, 42)')
    }
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${module} exceeds 390 pixels`)
    await screenshot(`${module}-mobile-dark`)
  }
  assert.deepEqual(errors, [])
  console.log('Part D populated browser proof passed: dashboards, filters, protected output, routing replay, task roles, notification failures, dialogs, keyboard use, dark mode, and 390-pixel containment.')
} finally { await browser.close(); await server.close() }
