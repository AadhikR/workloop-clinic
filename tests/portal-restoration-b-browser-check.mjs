  await page.getByRole('button', { name: 'Save branch' }).click()
  const branchStatus = page.locator('form.restoration-settings-sections').getByRole('status')
  await branchStatus.waitFor()
  assert.equal((await branchStatus.textContent()).trim(), 'Branch settings saved.')
  await page.screenshot({ path: path.join(evidence, 'organization-desktop.png'), fullPage: true })
