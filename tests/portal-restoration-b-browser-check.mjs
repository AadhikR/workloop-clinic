  await page.getByRole('alert').filter({ hasText: 'entries have been kept' }).waitFor()
  assert.equal(await page.getByLabel('End date', { exact: true }).inputValue(), '2028-01-01')
  await page.getByRole('button', { name: 'Confirm contract', exact: true }).click()
  await page.getByText('Contract action recorded.', { exact: true }).waitFor()
  const contractWrites = await page.evaluate(() => window.__restorationRequests.filter((item) => item.path.endsWith('/contracts/renew')))
